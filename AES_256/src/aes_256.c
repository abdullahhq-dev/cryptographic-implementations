// Key schedule function defining

static void SubWord(u8 input[4]) {
  for (int i = 0; i < 4; i++) {
    input[i] = sbox[input[i]];
  }
}

static void RotWord(u8 input[4]) {
  u8 temp = input[3];
  input[3] = input[0];
  input[0] = input[1];
  input[1] = input[2];
  input[2] = temp;
}

static u8 Rcon(int i) {
  u8 x = 0x01;
  for (int j = 1 ; j < i; j++) {
      x = xtime(x);
  }
  return x;
}

void key_expand(const u8 key[AES256_KEY_SIZE], u8 round_key[AES256_EXPANDED_KEY_SIZE]) {
  for (int i = 0; i < 32; i++) {
    round_key[i] = key[i];
  }
  
  int curr, prev, back;
  
  for (int i = AES256_NK; i < 60; i++) {
    curr = 4 * i; prev = 4 * (i - 1), back = 4 * (i - AES256_NK); // indices of the first bytes of corresponding words
    
    u8 temp[4];
    for (int j = 0; j < 4; j++) {
      temp[j] = round_key[prev + j];
    }
    
    if (i % AES256_NK == 0) {
      RotWord(temp);
      SubWord(temp);      
      temp[0] ^= Rcon(i / AES256_NK);   
    } else if (i % AES256_NK == 4) {
      SubWord(temp);
    }
    
    for (int j = 0; j < 4; j++) {
      round_key[curr + j] = round_key[back + j] ^ temp[j];
    }
  
  }
}


