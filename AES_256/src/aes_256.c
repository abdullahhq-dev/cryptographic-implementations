void load_state(state_t state, const u8 input[AES_BLOCK_SIZE]) {
  for (int i = 0; i < 4; ++i) {   
    for (int j = 0; j < 4; ++j) {
            state[j][i] = input[4*i + j];
    }
  }
}

void store_state(const state_t state, u8 output[AES_BLOCK_SIZE]) {
  for (int i = 0; i < 4; ++i) {   
    for (int j = 0; j < 4; ++j) {
      output[4*i + j] = state[j][i];
    }
  }
}

static void SubBytes(state_t state) {
  for (int i = 0; i < 4; ++i) {   
    for (int j = 0; j < 4; ++j) {
      state[j][i] = sbox[state[j][i]];
    }
  }
}

static void ShiftRows(state_t state) { 
  u8 temp;
  
  temp = state[1][0];
  state[1][0] = state[1][1];
  state[1][1] = state[1][2];
  state[1][2] = state[1][3];
  state[1][3] = temp;
  
  temp = state[2][0];
  state[2][0] = state[2][2];
  state[2][2] = temp;
  temp = state[2][1];
  state[2][1] = state[2][3];
  state[2][3] = temp;
  
  temp = state[3][0];
  state[3][0] = state[3][3];
  state[3][3] = state[3][2];
  state[3][2] = state[3][1];
  state[3][1] = temp;
}

// Now defining mix_columns function.
static inline u8 xtime(u8 x) {
  return ((x<<1) ^ ((x>>7) * 0x1b));
}

static inline u8 mul2(u8 x) {
  return xtime(x);
}

static inline u8 mul3(u8 x) {
  return xtime(x) ^ x;
}

static void MixColumns(state_t state) {
  for (int i = 0; i < 4; i++) {
  
    u8 a0 = state[0][i];
    u8 a1 = state[1][i];
    u8 a2 = state[2][i];
    u8 a3 = state[3][i];
    
    state[0][i] = mul2(a0) ^ mul3(a1) ^ a2 ^ a3;
    state[1][i] = a0 ^ mul2(a1) ^ mul3(a2) ^ a3;
    state[2][i] = a0 ^ a1 ^ mul2(a2) ^ mul3(a3);
    state[3][i] = mul3(a0) ^ a1 ^ a2 ^ mul2(a3);
  }
}

static void AddRoundKey(state_t state, const u8 round_key[AES_BLOCK_SIZE]) {
  for (int i = 0; i < 4; ++i) {   
    for (int j = 0; j < 4; ++j) {
      state[j][i] ^= round_key[4 * i + j];
    }
  }
}

