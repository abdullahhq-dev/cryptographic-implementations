#include <stdio.h>
#include "aes_256.h"

int main() {
u8 plain_text[AES_BLOCK_SIZE] = {
    0x00, 0x11, 0x22, 0x33,
    0x44, 0x55, 0x66, 0x77,
    0x88, 0x99, 0xaa, 0xbb,
    0xcc, 0xdd, 0xee, 0xff
};

u8 key[AES256_KEY_SIZE] = {
    0x00, 0x01, 0x02, 0x03,
    0x04, 0x05, 0x06, 0x07,
    0x08, 0x09, 0x0a, 0x0b,
    0x0c, 0x0d, 0x0e, 0x0f,
    0x10, 0x11, 0x12, 0x13,
    0x14, 0x15, 0x16, 0x17,
    0x18, 0x19, 0x1a, 0x1b,
    0x1c, 0x1d, 0x1e, 0x1f
};
                
  u8 round_key[AES256_EXPANDED_KEY_SIZE];
  key_expand(key, round_key);
  
  state_t state;
  load_state(state, plain_text);
  u8 cipher_text[AES_BLOCK_SIZE];
  encrypt_block(state, round_key);
  store_state(state, cipher_text);
  for ( int i = 0; i < AES_BLOCK_SIZE; i++) {
    printf("%02x", cipher_text[i]);
  }
  printf("\n");
  return 0;
}

